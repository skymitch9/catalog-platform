// ---------------------------------------------------------------------------
// Extraction
// ---------------------------------------------------------------------------

/** The one paragraph containing `anchor`, or a thrown explanation. */
export function paragraphFor(system, anchor) {
  const hits = paragraphsOf(system).filter((p) => p.includes(anchor));
  if (hits.length === 0) {
    throw new Error(
      `no upstream paragraph contains "${anchor}".\n` +
        'Either the prompt was restructured or the wording moved. Read GABI_SYSTEM\n' +
        'and update the anchor — do NOT loosen it into something that could match twice.',
    );
  }
  if (hits.length > 1) {
    throw new Error(
      `"${anchor}" matches ${hits.length} upstream paragraphs, so which one is meant is a guess.\n` +
        'Pick a longer anchor that appears exactly once.',
    );
  }
  return hits[0];
}

/** `{ key: verbatim upstream paragraph }`, in `SHARED` order. */
export function extractShared(system) {
  const out = {};
  for (const { key, anchor } of SHARED) out[key] = paragraphFor(system, anchor);
  return out;
}

/** The upstream text a delta pins, whichever kind it is. */
export function deltaText(system, delta) {
  if (delta.kind === 'section') {
    const text = sectionOf(system, delta.heading);
    if (text === null) {
      throw new Error(
        `upstream no longer has the section "${delta.heading}", which the Discord copy ` +
          'deliberately diverges from. Read the new shape and re-decide the delta.',
      );
    }
    return text;
  }
  return paragraphFor(system, delta.anchor);
}

/**
 * @returns {{ key: string, why: string, expected: string, actual: string, text: string }[]}
 *   one entry per delta whose upstream text moved. Empty = every delta is as
 *   last reviewed.
 */
export function checkDeltas(system) {
  const drift = [];
  for (const delta of DELTAS) {
    const text = deltaText(system, delta);
    const actual = sha256(text);
    if (actual !== delta.hash) drift.push({ key: delta.key, why: delta.why, expected: delta.hash, actual, text });
  }
  return drift;
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

/**
 * A TypeScript template literal holding `text` exactly.
 *
 * ⚠️ Escaping backslash, backtick and `${` even though today's prompt contains
 * none of the three: the day one appears, a generator that did not escape it
 * emits a file that either does not compile or — far worse — compiles into a
 * DIFFERENT string than the one upstream wrote.
 */
function asTemplateLiteral(text) {
  return `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``;
}

/** The generated region's body — everything BETWEEN the two markers. */
export function renderGenerated(shared) {
  const lines = [
    '/**',
    ' * ⚠️ **GENERATED — DO NOT EDIT BY HAND.** Rewritten by',
    ' * `scripts/sync-gabi-prompt.mjs`; `--check` runs as this package’s `pretest`',
    ' * and `pretypecheck`, so an edit here fails the next test run.',
    ' *',
    ` * Source: \`library_catalog/${SOURCE_RELATIVE.replace(/\\/g, '/')}\` → \`GABI_SYSTEM\`.`,
    ' *',
    ' * These are the paragraphs the two surfaces share BYTE FOR BYTE. The',
    ' * paragraphs Discord words differently are outside the markers, below,',
    ' * beside a comment naming the delta; the sync pins each of those upstream by',
    ' * hash, so an upstream edit to one of them fails the sync instead of passing',
    ' * unnoticed. `scripts/lib/gabi-prompt-sync.mjs` carries the whole argument.',
    ' */',
    'const SHARED = {',
  ];
  for (const { key, note } of SHARED) {
    lines.push(`  /** ${note} */`);
    lines.push(`  ${key}: ${asTemplateLiteral(shared[key])},`);
  }
  lines.push('} as const;');
  return lines.join('\n');
}

/** The current generated region of a target file, or `null` if unmarked. */
export function readGenerated(fileText) {
  const begin = fileText.indexOf(MARKER_BEGIN);
  const end = fileText.indexOf(MARKER_END);
  if (begin === -1 || end === -1 || end < begin) return null;
  return fileText.slice(begin + MARKER_BEGIN.length, end).replace(/^\n/, '').replace(/\n$/, '');
}

/** `fileText` with its generated region replaced. Throws if unmarked. */
export function spliceGenerated(fileText, body) {
  const begin = fileText.indexOf(MARKER_BEGIN);
  const end = fileText.indexOf(MARKER_END);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `the target file has no ${MARKER_BEGIN} / ${MARKER_END} pair.\n` +
        'Add the markers around the generated block before syncing; this script will\n' +
        'not guess where the boundary goes.',
    );
  }
  return `${fileText.slice(0, begin + MARKER_BEGIN.length)}\n${body}\n${fileText.slice(end)}`;
}
