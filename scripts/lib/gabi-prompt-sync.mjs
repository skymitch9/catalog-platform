// scripts/lib/gabi-prompt-sync.mjs
//
// ⚠️ THE ONE PLACE THAT KNOWS HOW GABI'S PROMPT IS SHARED BETWEEN TWO SURFACES.
//
// The canonical personality prompt is `GABI_SYSTEM` in
// `library_catalog/packages/research/src/gabi.ts`. The Discord bot carries a
// READ-CAPABLE subset of it in `apps/discord-worker/src/gabi-prompt.ts`. Until
// 2026-09-05 that subset was a HAND COPY with a comment asking somebody to
// remember, and its only test compared it against a literal it kept itself —
// so upstream drift was invisible by construction.
//
// This module is the fix. `scripts/sync-gabi-prompt.mjs` is its CLI and
// `apps/discord-worker/test/gabi-edge.test.ts` imports it so a drift fails a
// test rather than waiting for somebody to run a script.
//
// ## ⚠️ WHY IT IS NOT ONE CONTIGUOUS BLOCK — read this before "simplifying" it
//
// The obvious design is the one `sync-gabi-conversation.mjs` uses: copy a file
// wholesale into a generated/ directory. It does not work here, and the reason
// is structural rather than stylistic. **The two prompts differ INSIDE their
// sections, not after them.** Measured 2026-09-05, paragraph by paragraph:
//
// | Section | Shared paragraphs | Discord's deliberate delta |
// |---|---|---|
// | `## Who you are` | 2 of 3 | drops *", on their own site"* — Discord is not the site |
// | `## What you can do` | 0 of 1 | ENTIRELY different: upstream lists five WRITE tools and the auto/confirm lanes; Discord cannot write at all |
// | `## Finding the right book` | 1 of 3 | drops the `find_book` instruction; says *"a lookup"* for `find_book`, *"guess"* for *"guess an id"* |
// | `## Saying what is true` | 3 of 4 | says *"a tool call"* where upstream says `get_book` |
// | `## When something goes wrong` | 2 of 2 | none |
// | `## Remembering` | 0 of 1 | omitted — `DISCORD_SUFFIX` carries the 30-minute window instead |
//
// A single generated region would therefore have to contain text this surface
// must NOT say (five tool names that do not exist on Discord, an auto-write
// lane that would be a lie), and forcing the split would mean editing the
// prompt's semantics to make the tooling tidy. So:
//
//   - **SHARED paragraphs are EXTRACTED VERBATIM** into the generated region.
//     Eight of them. A change to any one upstream lands here mechanically.
//   - **DELTA paragraphs are PINNED BY HASH.** Nothing is copied — a second
//     hand copy would only move the original problem — but if upstream edits a
//     paragraph this surface deliberately words differently, the hash stops
//     matching, the sync FAILS, and it prints the new text so a human re-decides
//     the delta. That is the half a blind copy could never give.
//
// ⚠️ **What is deliberately OUT OF SCOPE: `GABI_EDGE_FULL`.** Both repos have
// one and they are deliberately NOT the same text — `gabi.ts`'s own header
// carries a three-row table of what had to be adapted for a surface with no
// voice note, no @mentions and a write path. They are near-duplicates that
// exist on purpose and are NOT interchangeable. Pinning them here would
// re-create the hand-copy problem one file to the left.

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export const MARKER_BEGIN = '// BEGIN generated by scripts/sync-gabi-prompt.mjs';
export const MARKER_END = '// END generated by scripts/sync-gabi-prompt.mjs';

/** Where the canonical prompt lives inside the library checkout. */
export const SOURCE_RELATIVE = join('packages', 'research', 'src', 'gabi.ts');

/** Where the copy lives in this repo. */
export const TARGET_RELATIVE = join('apps', 'discord-worker', 'src', 'gabi-prompt.ts');

// ---------------------------------------------------------------------------
// Reading the canonical prompt
// ---------------------------------------------------------------------------

/**
 * Pull the `GABI_SYSTEM` template literal out of the library's `gabi.ts`.
 *
 * ⚠️ A REGEX over source rather than an import, and that is the cheap choice on
 * purpose: importing would mean compiling a TypeScript package from another
 * repo, with its own dependency graph, to read one string constant. The regex
 * is anchored on the export statement and on the closing backtick-semicolon, and
 * it FAILS LOUDLY rather than returning something shorter than it should.
 */
export function extractGabiSystem(sourceText) {
  const m = /export const GABI_SYSTEM = `([\s\S]*?)`;\n/.exec(sourceText);
  if (!m) {
    throw new Error(
      'could not find `export const GABI_SYSTEM = `…`;` in the library source.\n' +
        'Either the constant was renamed or the file was restructured upstream.\n' +
        'Read it before changing this regex — a looser pattern here silently\n' +
        'captures the wrong string, which is the failure mode this whole module exists to stop.',
    );
  }
  const body = m[1];
  if (body.includes('${')) {
    throw new Error(
      'GABI_SYSTEM upstream now interpolates (`${…}`). It was a flat literal when\n' +
        'this sync was written, and every paragraph here is extracted verbatim on\n' +
        'that assumption. Read the new shape before touching this file.',
    );
  }
  if (body.trim().length === 0) throw new Error('GABI_SYSTEM is empty upstream — refusing to copy nothing.');
  return body;
}

export function readGabiSystem(libraryDir) {
  return extractGabiSystem(readFileSync(join(libraryDir, SOURCE_RELATIVE), 'utf8'));
}

/** Blank-line-separated blocks, trimmed of trailing whitespace, empties dropped. */
export function paragraphsOf(text) {
  return text
    .split(/\n{2,}/)
    .map((p) => p.replace(/\s+$/, ''))
    .filter((p) => p.length > 0);
}

/** Everything from one `## ` heading up to the next one (heading included). */
export function sectionOf(text, heading) {
  const lines = text.split('\n');
  const start = lines.indexOf(heading);
  if (start === -1) return null;
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i += 1) {
    if (lines[i].startsWith('## ')) {
      end = i;
      break;
    }
  }
  return lines.slice(start, end).join('\n').replace(/\s+$/, '');
}

export function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

